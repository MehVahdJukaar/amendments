package net.mehvahdjukaar.amendments.mixins;

import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import com.llamalad7.mixinextras.injector.wrapoperation.WrapOperation;
import net.mehvahdjukaar.amendments.common.HeldContainerPickup;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.entity.player.Inventory;
import net.minecraft.world.item.ItemStack;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;

@Mixin(ItemEntity.class)
public abstract class ItemEntityMixin {

    //done here and not event not to duplicate pickup delay checks
    @WrapOperation(method = "playerTouch", at = @At(value = "INVOKE", target = "Lnet/minecraft/world/entity/player/Inventory;add(Lnet/minecraft/world/item/ItemStack;)Z"))
    private boolean amendments$insertIntoHeldContainer(Inventory inventory, ItemStack stack, Operation<Boolean> original) {
        boolean absorbed = HeldContainerPickup.absorb(inventory.player, stack);
        if (stack.isEmpty()) return true;
        return original.call(inventory, stack) || absorbed;
    }
}
